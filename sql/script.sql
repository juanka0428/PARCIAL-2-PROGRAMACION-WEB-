-- script de creacion y datos de prueba (PostgreSQL)
-- ejecutar con: psql -U postgres -f script.sql

DROP DATABASE IF EXISTS gestion_consultas;
CREATE DATABASE gestion_consultas;

-- conectarse a la base nueva
\c gestion_consultas

CREATE TABLE usuarios (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username VARCHAR(50) NOT NULL UNIQUE,
  password VARCHAR(255) NOT NULL,
  nombre VARCHAR(60) NOT NULL,
  rol VARCHAR(20) NOT NULL
);

-- tabla independiente de medicos (se usa para el select del formulario)
CREATE TABLE medicos (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre VARCHAR(60) NOT NULL,
  especialidad VARCHAR(60) NOT NULL,
  usuario_id BIGINT UNIQUE REFERENCES usuarios (id)
);

CREATE TABLE consultas (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre_paciente VARCHAR(40) NOT NULL,
  motivo VARCHAR(100) NOT NULL,
  numero_consultorio INTEGER NOT NULL,
  hora_inicio TIME NOT NULL,
  hora_fin TIME NOT NULL,
  medico_id BIGINT NOT NULL REFERENCES medicos (id)
);

